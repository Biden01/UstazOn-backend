def get_system_prompt(subject: str | None = None) -> str:
    """
    Получить системный промпт с учетом предмета

    Args:
        subject: Код предмета (math, physics, etc.)

    Returns:
        Полный системный промпт
    """
    base_prompt = TEACHER_SYSTEM_PROMPT

    if subject and subject in SUBJECT_SPECIFIC_PROMPTS:
        subject_addition = SUBJECT_SPECIFIC_PROMPTS[subject]["system_addition"]
        return f"{base_prompt}\n\n{subject_addition}"

    return base_prompt


def get_quick_prompt(prompt_key: str) -> dict | None:
    """
    Получить быстрый промпт по ключу

    Args:
        prompt_key: Ключ промпта из QUICK_PROMPTS

    Returns:
        Словарь с данными промпта или None
    """
    return QUICK_PROMPTS.get(prompt_key)


def get_prompts_by_category(category: str) -> list[dict]:
    """
    Получить все промпты определенной категории

    Args:
        category: Категория (planning, teaching, assessment, etc.)

    Returns:
        Список промптов данной категории
    """
    return [
        {"key": key, **value}
        for key, value in QUICK_PROMPTS.items()
        if value.get("category") == category
    ]


def get_all_prompts_grouped() -> dict:
    """
    Получить все промпты, сгруппированные по категориям

    Returns:
        Словарь {категория: [промпты]}
    """
    grouped = {}
    for category_key, category_name in PROMPT_CATEGORIES.items():
        grouped[category_key] = {
            "name": category_name,
            "prompts": get_prompts_by_category(category_key)
        }
    return grouped
